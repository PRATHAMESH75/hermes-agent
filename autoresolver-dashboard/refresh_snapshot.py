#!/usr/bin/env python3
"""Build the Hermes Base dashboard snapshot from GitHub.

Collects every PR the autoresolver opened on the upstream repo, classifies
closed-but-unmerged PRs (salvaged / superseded / duplicate) from their
comments, and assembles a battle-log feed of recent reviews, comments,
pushes, merges and closures.

Requires an authenticated GitHub CLI (`gh auth status`). Stdlib only.

    python3 refresh_snapshot.py --out snapshot.json

The output is the document the page reads (`snapshot/latest` in the
artifact's database), plus one battle-log document per day (`feed/<YYYY-MM-DD>`)
so history survives after it leaves the --days window. `feed-batch.json`, written
next to --out, lists every write; pass it as `writes` to Claude's ArtifactData
tool with action=batch. Uploading only the snapshot still works:
    action=set, collection=snapshot, doc_id=latest, file_path=snapshot.json

Closures already classified in the dashboard's seed snapshot (verified by hand
against comments and upstream git history) keep that classification; only new
closures are classified here.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone

# A maintainer saying this PR's own work reached main.
SALVAGE_RE = re.compile(r"salvaged? (?:in|into|as|via)|cherry-?pick|co-authored|authorship (?:is |was )?preserved|"
                        r"(?:landed|merged) (?:on main )?via (?:PR )?#|with (?:co-author )?credit|both your commits", re.I)
DUPLICATE_RE = re.compile(r"\bduplicate\b|opened (?:first|earlier|~?\d+ ?min)|(?:filed|opened)[^.]{0,30}earlier|"
                          r"the earlier\b", re.I)
SUPERSEDED_RE = re.compile(r"supersed|already (?:fixed|landed|implemented|on main|resolves)|fixed on main|redundant|"
                           r"in favou?r of|now (?:implements|fixes|handles|resolves)|implemented on main|resolved (?:at|by)", re.I)
WITHDRAWN_RE = re.compile(r"withdraw|can(?:'|no)t reproduce|non-reproducible|no-op|maintainer review (?:is|confirms)", re.I)
NOTPLANNED_RE = re.compile(r"per (?:standing )?policy|not planned|out of core|belongs? in (?:the )?provider", re.I)
NOISE_RE = re.compile(r"generated by AI during triage", re.I)
PRIOR_REF = "origin/claude/fervent-darwin-lxs0ds:autoresolver-dashboard/seed-snapshot.json"
LABEL_KINDS = (("sweeper:implemented-on-main", "superseded"), ("sweeper:not-planned", "notplanned"), ("duplicate", "duplicate"))
FOOTER_RE = re.compile(r"\n-{3,}\s*\n_?Generated by \[Claude Code\].*", re.S)
MAX_DOC_BYTES = 240_000


def gh(path: str, **params) -> object:
    cmd = ["gh", "api", "-X", "GET", path]
    for k, v in params.items():
        cmd += ["-f", f"{k}={v}"]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"gh api {path} failed: {res.stderr.strip()}")
    return json.loads(res.stdout or "null")


def clean(body: str | None, limit: int = 240) -> str:
    text = FOOTER_RE.sub("", body or "")
    text = re.sub(r"```.*?```", " [code] ", text, flags=re.S)
    text = re.sub(r"<!--.*?-->", " ", text, flags=re.S)
    text = re.sub(r"(^|\s)(?:#{1,6}|>+)\s", " ", text)
    text = re.sub(r"[*`|]+", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1].rsplit(" ", 1)[0] + "…"


def split_title(title: str) -> tuple[str, int | None]:
    m = re.search(r"\s*\(#(\d+)\)\s*$", title)
    return (title[: m.start()] if m else title), (int(m.group(1)) if m else None)


def fetch_prs(repo: str, author: str) -> list[dict]:
    items, page = [], 1
    while True:
        data = gh("search/issues", q=f"author:{author} repo:{repo} is:pr", per_page=100, page=page,
                  sort="created", order="desc")
        items += data["items"]
        if len(data["items"]) < 100 or len(items) >= data["total_count"]:
            return items
        page += 1


def is_bot(login: str) -> bool:
    return login.endswith("[bot]") or login in ("coderabbitai", "github-actions")


def classify_comment(body: str, by_author: bool) -> str | None:
    """Closure kind a single closing-time comment implies, or None."""
    if by_author:
        # The autoresolver's own closing note: it never salvages its own work.
        for kind, rx in (("duplicate", DUPLICATE_RE), ("withdrawn", WITHDRAWN_RE), ("superseded", SUPERSEDED_RE)):
            if rx.search(body):
                return kind
        return None
    for kind, rx in (("salvaged", SALVAGE_RE), ("notplanned", NOTPLANNED_RE), ("duplicate", DUPLICATE_RE),
                     ("superseded", SUPERSEDED_RE)):
        if rx.search(body):
            return kind
    return None


def classify(repo: str, author: str, pr: dict) -> tuple[str | None, str | None, str | None]:
    """Return (closeKind, note, who) for a closed, unmerged PR, newest closing comment first."""
    comments = [c for c in gh(f"repos/{repo}/issues/{pr['n']}/comments", per_page=100) or []
                if not is_bot(c["user"]["login"]) and not NOISE_RE.search(c.get("body") or "")]
    cutoff = (datetime.fromisoformat(pr["closed"].replace("Z", "+00:00")) - timedelta(days=3)).strftime("%Y-%m-%dT%H:%M:%SZ")
    near = [c for c in comments if c["created_at"] >= cutoff] or comments
    for c in reversed(near):
        body, who = c.get("body") or "", c["user"]["login"]
        kind = classify_comment(body, who == author)
        if kind:
            return kind, clean(body, 180), who
    return None, None, None


def load_prior(path: str | None) -> dict[int, dict]:
    """Hand-verified closure classifications, keyed by PR number."""
    try:
        if path:
            text = open(path).read()
        else:
            res = subprocess.run(["git", "show", PRIOR_REF], capture_output=True, text=True)
            if res.returncode != 0:
                return {}
            text = res.stdout
        return {p["n"]: p for p in json.loads(text).get("prs", []) if p.get("closeKind")}
    except (OSError, ValueError):
        return {}


def feed_for(repo: str, author: str, pr: dict, since: str) -> list[dict]:
    n, ev = pr["n"], []
    if pr["created"] >= since:
        ev.append({"at": pr["created"], "who": author, "pr": n, "kind": "open",
                   "text": "Opened: " + pr["title"] + (f" (fixes #{pr['issue']})" if pr.get("issue") else "")})
    for c in gh(f"repos/{repo}/issues/{n}/comments", per_page=100) or []:
        if is_bot(c["user"]["login"]) or NOISE_RE.search(c.get("body") or ""):
            continue
        if c["created_at"] >= since and (c.get("body") or "").strip():
            ev.append({"at": c["created_at"], "who": c["user"]["login"], "pr": n, "kind": "comment",
                       "text": clean(c["body"])})
    for r in gh(f"repos/{repo}/pulls/{n}/reviews", per_page=100) or []:
        at = r.get("submitted_at") or ""
        if at < since:
            continue
        state = r.get("state")
        if state == "APPROVED":
            ev.append({"at": at, "who": r["user"]["login"], "pr": n, "kind": "approve",
                       "text": clean(r.get("body")) or "Approved."})
        elif state == "CHANGES_REQUESTED":
            ev.append({"at": at, "who": r["user"]["login"], "pr": n, "kind": "changes",
                       "text": clean(r.get("body")) or "Requested changes."})
        elif (r.get("body") or "").strip():
            ev.append({"at": at, "who": r["user"]["login"], "pr": n, "kind": "review", "text": clean(r["body"])})
    for c in gh(f"repos/{repo}/pulls/{n}/commits", per_page=100) or []:
        at = (c.get("commit") or {}).get("committer", {}).get("date") or ""
        initial = abs((datetime.fromisoformat(at.replace("Z", "+00:00")) -
                       datetime.fromisoformat(pr["created"].replace("Z", "+00:00"))).total_seconds()) < 3600 if at else True
        if at >= since and not initial:
            msg = (c["commit"].get("message") or "").splitlines()[0]
            ev.append({"at": at, "who": author, "pr": n, "kind": "push", "text": clean(msg, 160)})
    if pr["state"] == "merged" and (pr.get("closed") or "") >= since:
        full = gh(f"repos/{repo}/pulls/{n}")
        who = (full.get("merged_by") or {}).get("login") or "maintainer"
        pr["via"] = who
        ev.append({"at": pr["closed"], "who": who, "pr": n, "kind": "merge", "text": "Merged into main."})
    elif pr["state"] == "closed" and (pr.get("closed") or "") >= since:
        kind = "salvage" if pr.get("closeKind") == "salvaged" else "close"
        ev.append({"at": pr["closed"], "who": pr.get("via") or author, "pr": n, "kind": kind,
                   "text": pr.get("note") or "Closed without merging."})
    return ev


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default="NousResearch/hermes-agent")
    ap.add_argument("--author", default="PRATHAMESH75")
    ap.add_argument("--days", type=int, default=14, help="battle-log window in days")
    ap.add_argument("--feed-prs", type=int, default=100, help="most recently updated PRs to read threads from")
    ap.add_argument("--classify", type=int, default=200, help="recent closed PRs to classify from comments")
    ap.add_argument("--out", default="snapshot.json")
    ap.add_argument("--prior", help="snapshot whose closure classifications win (default: the seed on the dashboard branch)")
    args = ap.parse_args()

    raw = fetch_prs(args.repo, args.author)
    prs, updated = [], {}
    for it in raw:
        title, issue = split_title(it["title"])
        merged_at = (it.get("pull_request") or {}).get("merged_at")
        state = "merged" if merged_at else it["state"]
        pr = {"n": it["number"], "title": title, "issue": issue, "state": state,
              "created": it["created_at"], "comments": it.get("comments", 0),
              "labels": [l["name"] for l in it.get("labels", [])]}
        if it.get("closed_at"):
            pr["closed"] = merged_at or it["closed_at"]
        prs.append(pr)
        updated[pr["n"]] = it["updated_at"]

    prior = load_prior(args.prior)
    closed = [p for p in prs if p["state"] == "closed"]
    reused = 0
    for p in closed:
        known = prior.get(p["n"])
        if known:
            p.update({k: known[k] for k in ("closeKind", "note", "via") if known.get(k)})
            reused += 1
    for p in [p for p in closed if not p.get("closeKind")][: args.classify]:
        kind, note, who = classify(args.repo, args.author, p)
        if kind:
            p["closeKind"], p["note"], p["via"] = kind, note, who
            continue
        for label, lk in LABEL_KINDS:
            if label in p["labels"]:
                p["closeKind"], p["note"] = lk, f"Labelled {label} on GitHub."
                break

    since = (datetime.now(timezone.utc) - timedelta(days=args.days)).strftime("%Y-%m-%dT%H:%M:%SZ")
    recent = sorted((p for p in prs if updated[p["n"]] >= since), key=lambda p: updated[p["n"]], reverse=True)
    feed = []
    for p in recent[: args.feed_prs]:
        feed += feed_for(args.repo, args.author, p, since)
    feed.sort(key=lambda e: e["at"], reverse=True)

    snap = {
        "repo": args.repo, "author": args.author,
        "generatedAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source": "GitHub API via gh", "complete": True, "feedPrecision": "exact",
        "totals": {"all": len(prs), "open": sum(p["state"] == "open" for p in prs),
                   "merged": sum(p["state"] == "merged" for p in prs),
                   "closed": sum(p["state"] == "closed" for p in prs)},
        "prs": prs, "feed": feed[:120],
    }
    while len(json.dumps(snap)) > MAX_DOC_BYTES and snap["feed"]:
        snap["feed"] = snap["feed"][: len(snap["feed"]) * 3 // 4]
    with open(args.out, "w") as fh:
        json.dump(snap, fh)

    # One document per whole day in the window; the partial first day is skipped so a
    # shorter read never overwrites a fuller one stored by an earlier run.
    out_dir = os.path.dirname(os.path.abspath(args.out))
    by_day: dict[str, list] = {}
    for e in feed:
        if e["at"][:10] > since[:10]:
            by_day.setdefault(e["at"][:10], []).append(e)
    writes = []
    for day, events in sorted(by_day.items()):
        path = os.path.join(out_dir, f"feed-{day}.json")
        with open(path, "w") as fh:
            json.dump({"day": day, "events": sorted(events, key=lambda e: e["at"])}, fh)
        writes.append({"op": "set", "collection": "feed", "doc_id": day, "file_path": path})
    writes.append({"op": "set", "collection": "snapshot", "doc_id": "latest", "file_path": os.path.abspath(args.out)})
    with open(os.path.join(out_dir, "feed-batch.json"), "w") as fh:
        json.dump(writes, fh, indent=1)

    t = snap["totals"]
    print(f"wrote {args.out}: {t['all']} PRs ({t['open']} open, {t['merged']} merged, {t['closed']} closed), "
          f"{sum(1 for p in prs if p.get('closeKind'))} closures classified ({reused} from the verified seed), "
          f"{len(snap['feed'])} feed events, {len(by_day)} daily feed documents")
    return 0


if __name__ == "__main__":
    sys.exit(main())
